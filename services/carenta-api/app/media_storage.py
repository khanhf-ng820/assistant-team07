"""Object storage for sanitized capture media (#52).

Raw media must not depend on the API server's disk (plan §5), so files go to a
private Supabase Storage bucket. Only the backend writes there, using the
service-role key from ``app/settings.py``. Students can read their own folder
through the storage RLS policy in ``supabase/migrations``. Object paths are
always ``{owner_id}/{kind}/{media_id}.{ext}`` and are generated by the server,
never taken from the client's file name.
"""

from __future__ import annotations

import json
import re
import threading
import urllib.error
import urllib.parse
import urllib.request
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from typing import Protocol

from app.media import MediaKind
from app.settings import SupabaseSettings

CAPTURE_MEDIA_BUCKET = "capture-media"
_SAFE_SEGMENT = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_EXTENSIONS = frozenset({"jpg", "png", "m4a"})


class MediaStorageError(RuntimeError):
    """Storage failure with a message that never contains credentials."""


def build_object_path(owner_id: str, kind: MediaKind, media_id: str, extension: str) -> str:
    if kind not in ("receipt", "voice") or extension not in _EXTENSIONS:
        raise ValueError("Unsupported media kind or extension")
    for part in (owner_id, media_id):
        if not _SAFE_SEGMENT.match(part):
            raise ValueError("Object path segments must be URL-safe identifiers")
    return f"{owner_id}/{kind}/{media_id}.{extension}"


class MediaStorage(Protocol):
    def put(self, path: str, data: bytes, mime_type: str) -> None: ...

    def delete(self, paths: Iterable[str]) -> None: ...


@dataclass(frozen=True)
class HttpResult:
    status: int
    body: bytes


Transport = Callable[[urllib.request.Request, float], HttpResult]


def _urllib_transport(request: urllib.request.Request, timeout: float) -> HttpResult:
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return HttpResult(response.status, response.read())
    except urllib.error.HTTPError as exc:
        return HttpResult(exc.code, exc.read() or b"")


class SupabaseMediaStorage:
    """Supabase Storage REST client (``/storage/v1/object``)."""

    def __init__(
        self,
        settings: SupabaseSettings,
        bucket: str = CAPTURE_MEDIA_BUCKET,
        transport: Transport | None = None,
        timeout_seconds: float = 15.0,
    ) -> None:
        self._base = settings.url.rstrip("/") + "/storage/v1/object"
        self._key = settings.service_role_key
        self._bucket = bucket
        self._transport = transport or _urllib_transport
        self._timeout = timeout_seconds

    def _headers(self, content_type: str) -> dict[str, str]:
        key = self._key.get_secret_value()
        return {"Authorization": f"Bearer {key}", "apikey": key, "Content-Type": content_type}

    def _send(self, request: urllib.request.Request, action: str) -> HttpResult:
        try:
            result = self._transport(request, self._timeout)
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            raise MediaStorageError(f"Storage {action} failed: service unreachable.") from exc
        if not 200 <= result.status < 300:
            raise MediaStorageError(f"Storage {action} failed with HTTP {result.status}.")
        return result

    def put(self, path: str, data: bytes, mime_type: str) -> None:
        url = f"{self._base}/{self._bucket}/{urllib.parse.quote(path, safe='/')}"
        headers = self._headers(mime_type) | {"x-upsert": "false", "cache-control": "no-store"}
        self._send(urllib.request.Request(url, data=data, headers=headers, method="POST"), "upload")

    def delete(self, paths: Iterable[str]) -> None:
        prefixes = list(paths)
        if not prefixes:
            return
        body = json.dumps({"prefixes": prefixes}).encode()
        request = urllib.request.Request(
            f"{self._base}/{self._bucket}",
            data=body,
            headers=self._headers("application/json"),
            method="DELETE",
        )
        self._send(request, "delete")


class InMemoryMediaStorage:
    """Process-local storage for tests and Local Dev Mode (nothing touches disk)."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self.objects: dict[str, tuple[bytes, str]] = {}

    def put(self, path: str, data: bytes, mime_type: str) -> None:
        with self._lock:
            if path in self.objects:
                raise MediaStorageError("Storage upload failed: object already exists.")
            self.objects[path] = (bytes(data), mime_type)

    def delete(self, paths: Iterable[str]) -> None:
        with self._lock:
            for path in paths:
                self.objects.pop(path, None)
